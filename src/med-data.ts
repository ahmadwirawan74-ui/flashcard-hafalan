export type Who = "dewasa" | "anak";
export type RegKind = "kg" | "kgday" | "fixed" | "band" | "age" | "steps" | "text";

export interface Reg {
	who: Who;
	label: string;
	route: string;
	kind: RegKind;
	/** kg: per dosis per kg · kgday: per hari per kg · fixed: per dosis. */
	dose?: [number, number];
	/** Berapa kali per hari (untuk kgday: jumlah pembagian dosis). */
	freq?: number;
	every?: string;
	max?: number;
	maxDay?: number;
	maxDayKg?: number;
	/** Batas berat badan yang dipakai menghitung (mis. NAC maks 100 kg). */
	capKg?: number;
	/** Berdasarkan berat: `to` = batas atas kg (inklusif). */
	bands?: { to: number; dose: number; txt?: string }[];
	/** Berdasarkan usia: `to` = batas atas usia dalam bulan (inklusif). */
	ages?: { to: number; dose: number; txt?: string; freq?: number }[];
	steps?: { dose: number; max?: number; fixed?: number; txt: string }[];
	/** Usia minimal (bulan). */
	minAge?: number;
	/** Usia maksimal regimen (bulan). */
	maxAge?: number;
	/** Berat minimal regimen (kg, eksklusif). */
	minKg?: number;
	unit?: string;
	/** Komponen dasar perhitungan (mis. trimetoprim). */
	basis?: string;
	dur?: string;
	note?: string;
	text?: string;
}

export type PrepForm = "tab" | "kap" | "syr" | "drop" | "inj" | "neb" | "inf" | "supp" | "lain";
export interface Prep { label: string; form: PrepForm; mg?: number; mgMl?: number }

